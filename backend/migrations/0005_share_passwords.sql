-- Миграция 0005: пароли для share-ссылок.
--
-- Пароль хранится как argon2id-хеш (см. handlers::shares). NULL означает,
-- что ссылка доступна без пароля (старые ссылки, созданные до этого
-- обновления). Пароль задаётся только при создании ссылки; сбросить его
-- можно отзывом ссылки и созданием новой.
ALTER TABLE file_shares ADD COLUMN IF NOT EXISTS password_hash TEXT;